create table if not exists public.gardens (
  id           uuid primary key default gen_random_uuid(),
  member_code  text not null unique,
  name         text,
  created_at   timestamptz not null default now()
);

create table if not exists public.garden_members (
  id          uuid primary key default gen_random_uuid(),
  garden_id   uuid not null references public.gardens(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  role        text not null default 'staff',
  created_at  timestamptz not null default now(),
  unique (garden_id, user_id)
);

create table if not exists public.foods (
  id          bigint generated by default as identity primary key,
  garden_id   uuid references public.gardens(id) on delete cascade,
  name        text not null,
  created_at  timestamptz not null default now()
);

create table if not exists public.food_aliases (
  id       bigint generated by default as identity primary key,
  food_id  bigint not null references public.foods(id) on delete cascade,
  alias    text not null
);

create table if not exists public.cooking_methods (
  id          bigint generated by default as identity primary key,
  food_id     bigint not null references public.foods(id) on delete cascade,
  garden_id   uuid references public.gardens(id) on delete cascade,
  phase1      text,
  phase2      text,
  phase3      text,
  phase4      text,
  phase5      text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (food_id, garden_id)
);

create table if not exists public.children (
  id          uuid primary key default gen_random_uuid(),
  garden_id   uuid not null references public.gardens(id) on delete cascade,
  name        text not null,
  age_month   integer,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.child_food_restrictions (
  id          uuid primary key default gen_random_uuid(),
  child_id    uuid not null references public.children(id) on delete cascade,
  food_id     bigint not null references public.foods(id) on delete cascade,
  cannot_eat  boolean not null default true,
  note        text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.accidents (
  id          uuid primary key default gen_random_uuid(),
  garden_id   uuid references public.gardens(id) on delete set null,
  child_id    uuid references public.children(id) on delete set null,
  food_id     bigint not null references public.foods(id),
  content     text not null,
  is_public   boolean not null default false,
  created_at  timestamptz not null default now()
);

