-- ---------------------------------------------------------------------------
-- updated_at trigger helper
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_cooking_methods_updated_at on public.cooking_methods;
create trigger trg_cooking_methods_updated_at
  before update on public.cooking_methods
  for each row execute function public.set_updated_at();

drop trigger if exists trg_children_updated_at on public.children;
create trigger trg_children_updated_at
  before update on public.children
  for each row execute function public.set_updated_at();

drop trigger if exists trg_child_food_restrictions_updated_at on public.child_food_restrictions;
create trigger trg_child_food_restrictions_updated_at
  before update on public.child_food_restrictions
  for each row execute function public.set_updated_at();

