-- Helper: the garden_id(s) the current auth.uid() belongs to.
-- (Expressed inline as a subquery in each policy below, since Postgres RLS
-- policies can't call a SECURITY DEFINER function that itself queries a
-- RLS-protected table without care; the inline subquery form is simplest
-- and keeps garden_members' own policy authoritative.)

-- ---- gardens -----------------------------------------------------------
-- Only the service role (which bypasses RLS) reads/writes this table today
-- (registration, login lookup, account deletion all go through supabaseAdmin).
-- No anon/authenticated policies are defined, so normal clients get zero rows.

-- ---- garden_members ------------------------------------------------------
create policy "members can read their own membership"
  on public.garden_members for select
  to authenticated
  using (user_id = auth.uid());

-- ---- foods -----------------------------------------------------------
create policy "anyone can read shared foods"
  on public.foods for select
  to anon, authenticated
  using (garden_id is null);

create policy "members can read their garden's foods"
  on public.foods for select
  to authenticated
  using (
    garden_id in (select gm.garden_id from public.garden_members gm where gm.user_id = auth.uid())
  );

create policy "members can insert foods for their garden"
  on public.foods for insert
  to authenticated
  with check (
    garden_id in (select gm.garden_id from public.garden_members gm where gm.user_id = auth.uid())
  );

create policy "members can update their garden's foods"
  on public.foods for update
  to authenticated
  using (
    garden_id in (select gm.garden_id from public.garden_members gm where gm.user_id = auth.uid())
  )
  with check (
    garden_id in (select gm.garden_id from public.garden_members gm where gm.user_id = auth.uid())
  );

create policy "members can delete their garden's foods"
  on public.foods for delete
  to authenticated
  using (
    garden_id in (select gm.garden_id from public.garden_members gm where gm.user_id = auth.uid())
  );

